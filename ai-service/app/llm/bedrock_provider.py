"""AWS Bedrock provider.

Generates behavioural Python (``pytest``) unit tests for GP / C++ / Python
source using an LLM hosted on Amazon Bedrock (Claude, Llama or Titan).

The provider degrades gracefully: if ``boto3`` is missing, no AWS credentials
are configured, or the API call fails, ``available()`` returns ``False`` (or
``generate`` raises :class:`BedrockUnavailable`) and the factory falls back to
the offline baseline. This keeps local development working without AWS access.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

from .base import GeneratedSuite, TestGenerationProvider

DEFAULT_MODEL_ID = "anthropic.claude-3-5-sonnet-20240620-v1:0"

_PROMPT = """You are a senior test engineer for NeoXam GP, an investment-accounting
back-office platform whose components are written in C/C++ and a SQL-flavoured
rule DSL. Analyse the {language} source below and produce a Python `pytest`
suite that unit-tests the extracted units.

Rules:
- Use only the standard library plus `pytest`.
- Target the language's units: {units}
- Because {language} cannot be imported in Python, isolate each unit behind a
  small adapter (e.g. a subprocess call, ctypes/cffi binding, or an injected
  mock). Where real execution is impossible, write a precise contract test and
  mark it `@pytest.mark.skip(reason=...)` rather than faking a pass.
- Cover edge cases and boundary values, not just the happy path.
- Return ONLY one fenced ```python code block, no prose.

Source:
```{language}
{source}
```"""


class BedrockUnavailable(RuntimeError):
    """Raised when Bedrock cannot be used and the caller should fall back."""


def _has_credentials() -> bool:
    if os.environ.get("AWS_ACCESS_KEY_ID") and os.environ.get("AWS_SECRET_ACCESS_KEY"):
        return True
    if os.environ.get("AWS_PROFILE") or os.environ.get("AWS_SESSION_TOKEN"):
        return True
    credentials = Path.home() / ".aws" / "credentials"
    return credentials.exists()


class BedrockProvider(TestGenerationProvider):
    name = "bedrock"

    def __init__(self, model_id: str | None = None, region: str | None = None) -> None:
        self.model_id = model_id or os.environ.get("BEDROCK_MODEL_ID", DEFAULT_MODEL_ID)
        self.region = (
            region
            or os.environ.get("AWS_REGION")
            or os.environ.get("AWS_DEFAULT_REGION")
            or "us-east-1"
        )

    def available(self) -> bool:
        if os.environ.get("SMARTJOB_DISABLE_BEDROCK") == "1":
            return False
        try:
            import boto3  # noqa: F401
        except Exception:
            return False
        return _has_credentials()

    def describe(self) -> dict[str, Any]:
        return {
            "provider": self.name,
            "available": self.available(),
            "model": self.model_id,
            "region": self.region,
        }

    def generate(self, source: str, analysis: dict[str, Any], language: str) -> GeneratedSuite:
        if not self.available():
            raise BedrockUnavailable("AWS Bedrock is not configured (missing credentials or boto3)")
        try:
            import boto3
        except Exception as error:  # pragma: no cover - guarded by available()
            raise BedrockUnavailable(str(error)) from error

        client = boto3.client("bedrock-runtime", region_name=self.region)
        prompt = _PROMPT.format(
            language=language,
            units=", ".join(analysis["functions"] + analysis["classes"]) or "the module",
            source=source,
        )
        body = self._build_body(prompt)
        response = client.invoke_model(
            modelId=self.model_id,
            body=json.dumps(body),
            accept="application/json",
            contentType="application/json",
        )
        payload = json.loads(response["body"].read())
        text = self._extract_text(payload)
        test_source = self._extract_code(text)
        return GeneratedSuite(
            test_source=test_source,
            provider=self.name,
            model=self.model_id,
            rationale=text.strip()[:1000],
            notes=[f"Generated by {self.model_id} on AWS Bedrock ({self.region})."],
        )

    # ----------------------------------------------------------------- helpers
    def _build_body(self, prompt: str) -> dict[str, Any]:
        if "anthropic" in self.model_id:
            return {
                "anthropic_version": "bedrock-2023-05-31",
                "max_tokens": 4096,
                "temperature": 0.2,
                "messages": [{"role": "user", "content": prompt}],
            }
        if "meta" in self.model_id:
            return {"prompt": prompt, "max_gen_len": 2048, "temperature": 0.2, "top_p": 0.9}
        if "amazon" in self.model_id:
            return {
                "inputText": prompt,
                "textGenerationConfig": {"maxTokenCount": 2048, "temperature": 0.2, "topP": 0.9},
            }
        return {
            "anthropic_version": "bedrock-2023-05-31",
            "max_tokens": 4096,
            "temperature": 0.2,
            "messages": [{"role": "user", "content": prompt}],
        }

    def _extract_text(self, payload: dict[str, Any]) -> str:
        if isinstance(payload.get("content"), list) and payload["content"]:
            return payload["content"][0].get("text", "")
        if "generation" in payload:
            return payload["generation"]
        if isinstance(payload.get("results"), list) and payload["results"]:
            return payload["results"][0].get("outputText", "")
        if "outputText" in payload:
            return payload["outputText"]
        return json.dumps(payload)

    def _extract_code(self, text: str) -> str:
        fence = "```"
        if fence in text:
            parts = text.split(fence)
            for part in parts:
                candidate = part
                if candidate.startswith("python"):
                    candidate = candidate[len("python"):]
                candidate = candidate.strip("\n")
                if "def test_" in candidate or "import pytest" in candidate:
                    return candidate if candidate.endswith("\n") else candidate + "\n"
        return text if text.endswith("\n") else text + "\n"
